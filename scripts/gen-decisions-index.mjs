#!/usr/bin/env node
// Generates docs/DECISIONS.md from docs/decisions/*.md, and writes the reciprocal
// "amended by" banner into each amended decision's own file (#564, DEC-141).
//
// Run: `npm run gen:decisions`. `npm run check:decisions` fails if the output is stale,
// so forgetting to run it is a red build rather than an invisible defect — which is the
// actual fix for DEC-127's decay. There is still a step; it just can't be skipped quietly.
//
// The banner matters as much as the index. Audit shard Z2 found 28 supersede-class edges
// where the amending DEC updated itself and never its target, and noted that a reader
// arriving by Ctrl-F, a code comment, or another doc's citation lands in the body and
// reads the retired answer with no signal. An index-only pointer only helps the reader
// who came via the index. Nobody does.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

export const DIR = 'docs/decisions'
export const OUT = 'docs/DECISIONS.md'
export const SPEC = 'docs/SPEC.md'
const PREAMBLE = `${DIR}/_preamble.md`

// Topic order is the index's reading order and is not derivable from the files — it is
// editorial. An unknown topic in frontmatter fails the check rather than appending
// silently to the bottom, where nobody would see it.
export const TOPICS = [
  'Core architecture & engine mechanics',
  'Availability & commitment rules',
  'Seats, shifts & state machine',
  'Staffing engine — asks, escalation, At-Risk board & cockpit',
  'Reliability scoring',
  'Timing — horizons, deadlines & vessel clock',
  'Crew, vessels & manning model',
  'Xola ingest & import',
  'Messaging, presence & doorbell',
  'Outbound notifications & operator relay',
  'Crew self-serve, auth & admin identity',
  'Reservations & payments',
  'UI, brand & frontend patterns',
  'Deployment, infra & versioning',
  'Open questions',
]

// `supersedes` strikes the target's row; everything else annotates it. The vocabulary is
// the one already in use across the record — shard Z2's point was that it was prose, and
// prose is not checkable. Rendered as the past participle a back-pointer wants.
export const RELATIONS = {
  supersedes: 'superseded by',
  amends: 'amended by',
  revises: 'revised by',
  refines: 'refined by',
  reverses: 'reversed by',
  retires: 'retired by',
  extends: 'extended by',
  corrects: 'corrected by',
  resolves: 'resolved by',
  reframes: 'reframed by',
}

const BANNER_OPEN = '<!-- amended-by: generated by `npm run gen:decisions` — do not edit by hand -->'
const BANNER_CLOSE = '<!-- /amended-by -->'

// The DEC→SPEC leg (#590). DEC-141 made the DEC→DEC leg checkable; this is the other half
// of the pattern the 2026-07-25 audit named as its largest finding class — a change that
// lands in a decision and never in the spec it claims to change.
//
// Frontmatter keys whose value is a list of entries rather than a scalar. Enumerated
// because the parser has to know a list is open before it reads the first `- ` under it.
const LISTS = new Set(['amends', 'amends_spec'])
const SPEC_OPEN = '<!-- amended-by-dec: generated by `npm run gen:decisions` — do not edit by hand -->'
const SPEC_CLOSE = '<!-- /amended-by-dec -->'

/**
 * Section number → the index of its heading line, for every numbered heading in SPEC.
 *
 * Deliberately strict about what counts as a section: `## 2.4 Assignment View` and
 * `# 4. Parked …` both resolve, `### Booking availability` does not. A decision may only
 * anchor to a numbered section, because an unnumbered heading's text is prose that gets
 * reworded, and an anchor that silently stops resolving is the failure this check exists
 * to prevent.
 * @param {string} text
 */
export function specSections(text) {
  const sections = new Map()
  text.split('\n').forEach((line, i) => {
    const m = line.match(/^#{1,4} (\d+(?:\.\d+)*)\.? /)
    if (m && !sections.has(m[1])) sections.set(m[1], i)
  })
  return sections
}

/** `§2.4` / `2.4` → `2.4`. Tolerates the section sign the record writes in prose. */
export const sectionNumber = (s) => String(s).replace(/^§/, '').replace(/\.$/, '')

/**
 * Minimal frontmatter reader for exactly the shape this project writes — no YAML
 * dependency for one flat block plus one list of three scalars. A shape it can't parse
 * is an error, not a silent skip.
 * @param {string} text
 */
export function parseFrontmatter(text) {
  if (!text.startsWith('---\n')) throw new Error('no frontmatter')
  const end = text.indexOf('\n---\n', 3)
  if (end === -1) throw new Error('unterminated frontmatter')
  const block = text.slice(4, end)
  const body = text.slice(end + 5)

  const unquote = (s) =>
    s.startsWith('"') && s.endsWith('"')
      ? s.slice(1, -1).replace(/\\"/g, '"').replace(/\\\\/g, '\\')
      : s

  const meta = { amends: [], amends_spec: [] }
  let list = null
  let entry = null
  for (const raw of block.split('\n')) {
    if (!raw.trim()) continue
    // A list item opens a new entry under whichever list key is currently open. Keyed on
    // the indent and the dash rather than on a specific first field, because `amends`
    // entries open with `id` and `amends_spec` entries open with `section`.
    const item = raw.match(/^ {2}- (\w+): (.*)$/)
    if (item) {
      if (!list) throw new Error(`list item outside any list: ${JSON.stringify(raw)}`)
      entry = { [item[1]]: unquote(item[2]) }
      meta[list].push(entry)
      continue
    }
    const nested = raw.match(/^ {4}(\w+): (.*)$/)
    if (nested && entry) {
      entry[nested[1]] = unquote(nested[2])
      continue
    }
    const top = raw.match(/^(\w+): ?(.*)$/)
    if (top) {
      if (LISTS.has(top[1])) {
        list = top[1]
        entry = null
        continue
      }
      meta[top[1]] = unquote(top[2])
      continue
    }
    throw new Error(`unparseable frontmatter line: ${JSON.stringify(raw)}`)
  }
  return { meta, body }
}

// Where the non-numeric families sit in the record's chronology. The pre-split
// DECISIONS.md was written in decision order, and it placed all five between DEC-014 and
// DEC-015 (`git show f41a895^:docs/DECISIONS.md`, lines 374–472). That is the evidence for
// this number; it is not an editorial choice.
//
// It matters because the id is the ONLY time proxy the record carries — no decision file
// has a `decided:` field — and the backwards-amendment guard in check-decisions.mjs is
// exactly the assertion that id order tracks time. A family with no position makes that
// guard unrunnable, which is how it came to be silently inert for five ids (#589).
const PRE_015 = 14.5
const FAMILIES = new Set(['MSG', 'ROLE', 'DATA'])

/**
 * A decision's position in the record, or null if it has none.
 *
 * `DEC-TBD` is null on purpose: it is the open-questions container, not a decision taken
 * at a point in time, so there is no honest answer. Anything new and unrecognized is null
 * for the same reason — null is what makes the next non-uniform id visible instead of
 * silent, which was the whole defect in #589.
 * @param {string} id
 */
export function rank(id) {
  const n = id.match(/^DEC-(\d+)$/)
  if (n) return { n: Number(n[1]), family: '', seq: 0 }
  const f = id.match(/^DEC-([A-Z]+)-(\d+)$/)
  if (f && FAMILIES.has(f[1])) return { n: PRE_015, family: f[1], seq: Number(f[2]) }
  return null
}

/**
 * Negative if `a` comes before `b`, positive if after, 0 if the same position — and
 * **null when the record cannot say**, which callers must handle rather than treat as
 * equal.
 *
 * Cross-family is null even though the pre-split file listed MSG-1/2/3, then ROLE-1, then
 * DATA-1: that is document order within one sitting, not evidence about when each was
 * decided. Ranking them off it would manufacture a fact the record does not have.
 * @param {string} a
 * @param {string} b
 */
export function compareDecisionIds(a, b) {
  const [x, y] = [rank(a), rank(b)]
  if (!x || !y) return null
  if (x.n !== y.n) return x.n - y.n
  if (x.family !== y.family) return null
  return x.seq - y.seq
}

// Sort order for the index and the banner lists: the same ranking, so display order and
// the guard can never drift apart. Unrankable ids sort to the tail alphabetically —
// arbitrary, but sorting must be total where comparison is allowed to abstain.
const sortKey = (id) => {
  const r = rank(id)
  return r ? [0, r.n, r.family, r.seq, ''] : [1, 0, '', 0, id]
}
const byId = (a, b) => {
  const [x, y] = [sortKey(a), sortKey(b)]
  return x[0] - y[0] || x[1] - y[1] || x[2].localeCompare(y[2]) || x[3] - y[3] || x[4].localeCompare(y[4])
}

export function load(dir = DIR) {
  const files = readdirSync(dir).filter((f) => f.startsWith('DEC-') && f.endsWith('.md'))
  const decisions = new Map()
  for (const file of files) {
    const text = readFileSync(`${dir}/${file}`, 'utf8')
    let parsed
    try {
      parsed = parseFrontmatter(text)
    } catch (e) {
      throw new Error(`${dir}/${file}: ${e.message}`)
    }
    const { meta, body } = parsed
    if (!meta.id) throw new Error(`${dir}/${file}: no id`)
    if (decisions.has(meta.id)) throw new Error(`${dir}/${file}: duplicate id ${meta.id}`)
    decisions.set(meta.id, { ...meta, file, body, text })
  }
  return decisions
}

/** target id -> [{ from, relation, scope }] */
export function reverseGraph(decisions) {
  const incoming = new Map()
  for (const [id, d] of decisions) {
    for (const a of d.amends ?? []) {
      if (!incoming.has(a.id)) incoming.set(a.id, [])
      incoming.get(a.id).push({ from: id, relation: a.relation, scope: a.scope })
    }
  }
  for (const list of incoming.values()) list.sort((p, q) => byId(p.from, q.from))
  return incoming
}

const phrase = (e) => {
  const verb = RELATIONS[e.relation]
  return e.scope ? `${verb} ${e.from} — ${e.scope}` : `${verb} ${e.from}`
}

/** The banner that goes at the top of an amended decision's own file. */
export function banner(edges) {
  const lines = edges.map((e) => `> **${phrase(e)[0].toUpperCase()}${phrase(e).slice(1)}**`)
  return [BANNER_OPEN, ...lines, BANNER_CLOSE].join('\n')
}

/**
 * Body with any existing generated banner removed.
 *
 * Only the seam left by the removal is normalized. A global blank-line collapse here
 * would make the generator a non-fixed-point for any amended decision whose body has a
 * double blank line anywhere in it: the first run writes the file, and the next
 * `check:decisions` re-generates, collapses that unrelated gap, and reports the file it
 * just wrote as stale — a red build with no author error to fix.
 */
export function stripBanner(body) {
  const open = body.indexOf(BANNER_OPEN)
  if (open === -1) return body
  const close = body.indexOf(BANNER_CLOSE, open)
  const before = body.slice(0, open).replace(/\n+$/, '')
  const after = body.slice(close + BANNER_CLOSE.length).replace(/^\n+/, '')
  return `${before}\n\n${after}`
}

/** section number -> [{ from, scope }] — the DEC→SPEC edges, inverted onto the spec. */
export function specGraph(decisions) {
  const incoming = new Map()
  for (const [id, d] of decisions) {
    for (const a of d.amends_spec ?? []) {
      const sec = sectionNumber(a.section)
      if (!incoming.has(sec)) incoming.set(sec, [])
      incoming.get(sec).push({ from: id, scope: a.scope })
    }
  }
  for (const list of incoming.values()) list.sort((p, q) => byId(p.from, q.from))
  return incoming
}

/**
 * The block that goes under an amended SPEC section's heading.
 *
 * One fixed verb, unlike the DEC→DEC banner's ten-relation vocabulary. The distinctions
 * that vocabulary draws (`supersedes` vs `refines` vs `corrects`) matter between decisions,
 * where the question is which one is now authoritative. Against the spec there is only one
 * question a reader has — *is what I am reading still true?* — and the scope answers it.
 */
export function specBanner(edges) {
  const lines = edges.map((e) => (e.scope ? `> **Amended by ${e.from} — ${e.scope}**` : `> **Amended by ${e.from}**`))
  return [SPEC_OPEN, ...lines, SPEC_CLOSE].join('\n')
}

/**
 * SPEC text with every generated block removed — the exact inverse of the insertion in
 * `renderSpec`, so `strip(render(x)) === x` for a pristine spec.
 */
export function stripSpecBlocks(text) {
  const out = []
  let skipping = false
  for (const line of text.split('\n')) {
    if (line === SPEC_OPEN) {
      skipping = true
      // Exactly one blank line was inserted ahead of the block; take back exactly one.
      if (out[out.length - 1] === '') out.pop()
      continue
    }
    if (skipping) {
      if (line === SPEC_CLOSE) skipping = false
      continue
    }
    out.push(line)
  }
  return out.join('\n')
}

/**
 * SPEC with a generated block under each amended section's heading.
 *
 * An unresolvable section is skipped rather than thrown on: `check()` reports it as an
 * author error with the section number in the message, which is a better failure than the
 * generator dying halfway through a write.
 */
export function renderSpec(text, incoming) {
  const base = stripSpecBlocks(text)
  const sections = specSections(base)
  const at = new Map()
  for (const [sec, edges] of incoming) {
    const line = sections.get(sec)
    if (line !== undefined) at.set(line, edges)
  }
  const out = []
  base.split('\n').forEach((line, i) => {
    out.push(line)
    if (at.has(i)) out.push('', specBanner(at.get(i)))
  })
  return out.join('\n')
}

/** Full file text for a decision, with its banner in the right place (or absent). */
export function renderDecision(d, edges) {
  const fm = ['---', `id: ${d.id}`, `title: ${quote(d.title)}`, `topic: ${quote(d.topic)}`]
  if (d.amends?.length) {
    fm.push('amends:')
    for (const a of d.amends) {
      fm.push(`  - id: ${a.id}`, `    relation: ${a.relation}`, `    scope: ${quote(a.scope ?? '')}`)
    }
  }
  if (d.amends_spec?.length) {
    fm.push('amends_spec:')
    for (const a of d.amends_spec) {
      fm.push(`  - section: ${quote(sectionNumber(a.section))}`, `    scope: ${quote(a.scope ?? '')}`)
    }
  }
  fm.push('---')

  const clean = stripBanner(d.body).replace(/^\n+/, '').replace(/\s+$/, '')
  const [heading, ...rest] = clean.split('\n')
  const tail = rest.join('\n').replace(/^\n+/, '')
  // Banner sits immediately under the heading — the first thing a Ctrl-F reader sees.
  const parts = edges?.length ? [heading, '', banner(edges), '', tail] : [heading, '', tail]
  return `${fm.join('\n')}\n\n${parts.join('\n').replace(/\s+$/, '')}\n`
}

const quote = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`

export function renderIndex(decisions, incoming, preamble) {
  const out = [preamble.replace(/\s+$/, ''), '', '## Index', '']

  const byTopic = new Map(TOPICS.map((t) => [t, []]))
  for (const [id, d] of decisions) {
    if (!byTopic.has(d.topic)) throw new Error(`${d.file}: unknown topic ${JSON.stringify(d.topic)}`)
    byTopic.get(d.topic).push(id)
  }

  let indexed = 0
  for (const topic of TOPICS) {
    const ids = byTopic.get(topic).sort(byId)
    if (!ids.length) continue
    out.push(`### ${topic}`)
    for (const id of ids) {
      const d = decisions.get(id)
      const edges = incoming.get(id) ?? []
      const total = edges.filter((e) => e.relation === 'supersedes')
      const partial = edges.filter((e) => e.relation !== 'supersedes')

      // The strike covers id AND title, so the row reads as one retired statement. Putting
      // the relation after it — rather than between id and title — keeps a single em-dash
      // per clause; the earlier shape produced "DEC-013 — <scope> — <title>", unreadable.
      let row = total.length ? `- ~~${id} — ${d.title}~~ → ${total.map(phrase).join('; ')}` : `- ${id} — ${d.title}`
      if (partial.length) row += ` _(${total.length ? 'also ' : ''}${partial.map(phrase).join('; ')})_`
      out.push(row)
      indexed++
    }
    out.push('')
  }

  out.push(
    `_Indexed ${indexed} of ${decisions.size} DECs. **This file is GENERATED** by \`npm run gen:decisions\` —`,
    `edit \`${DIR}/DEC-*.md\`, not this file. \`npm run check:decisions\` fails on a stale index, a`,
    'duplicate id, an unknown topic, an unknown relation, a forward-pointing amendment, or a',
    'reference to a decision that does not exist._',
    '',
  )
  return out.join('\n')
}

export function generate(dir = DIR, specPath = SPEC) {
  const decisions = load(dir)
  const incoming = reverseGraph(decisions)
  const preamble = readFileSync(PREAMBLE, 'utf8')
  const files = new Map()
  for (const [id, d] of decisions) files.set(d.file, renderDecision(d, incoming.get(id)))
  const specIncoming = specGraph(decisions)
  const spec = renderSpec(readFileSync(specPath, 'utf8'), specIncoming)
  return { index: renderIndex(decisions, incoming, preamble), files, spec, decisions, incoming, specIncoming }
}

if (process.argv[1]?.endsWith('gen-decisions-index.mjs')) {
  const { index, files, spec, decisions, incoming, specIncoming } = generate()
  let rewritten = 0
  for (const [file, text] of files) {
    const path = `${DIR}/${file}`
    if (readFileSync(path, 'utf8') !== text) {
      writeFileSync(path, text)
      rewritten++
    }
  }
  writeFileSync(OUT, index)
  if (readFileSync(SPEC, 'utf8') !== spec) writeFileSync(SPEC, spec)
  const banners = [...incoming.keys()].length
  console.log(
    `✓ ${OUT} regenerated from ${decisions.size} decisions — ` +
      `${banners} carry an amended-by banner, ${rewritten} file${rewritten === 1 ? '' : 's'} rewritten, ` +
      `${specIncoming.size} SPEC section${specIncoming.size === 1 ? '' : 's'} annotated`,
  )
}
